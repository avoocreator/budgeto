const DICTS: Record<Lang, Dict> = { id, en };
interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>()(
  persist(
    (set) => ({ lang: "id", setLang: (l) => set({ lang: l }) }),
    { name: "budgeto-lang" }
  )
);

/** Default mengikuti bahasa sistem saat pertama kali (tidak menimpa pilihan tersimpan). */
export function initLangFromSystem(): void {
  const stored = localStorage.getItem("budgeto-lang");
  if (stored) return; // sudah pernah disimpan (persist)
  const sys = navigator.language?.toLowerCase() ?? "id";
  useLang.getState().setLang(sys.startsWith("id") ? "id" : "en");
}

export function dictOf(lang: Lang): Dict {
  return DICTS[lang] ?? id;
}

export function tOf(lang: Lang): Dict {
  return dictOf(lang);
}

export function localeOf(lang: Lang): string {
  return lang === "id" ? "id-ID" : "en-US";
}
